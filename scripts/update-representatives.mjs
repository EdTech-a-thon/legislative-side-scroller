import { writeFileSync } from 'node:fs';

// House members change with every vacancy and special election, so this is refreshed on the
// same monthly schedule as the officeholder data.
//
// REVIEW BEFORE MERGING A JANUARY RUN: a new Congress is seated in January, and mid-decade
// redistricting means the ZIP-to-district map used for an election is not the map for the
// Congress seated before it. Both files below must describe *currently seated* districts.
// Spot-check a redistricted state against clerk.house.gov before merging a January refresh.

const rosterUrl = 'https://unitedstates.github.io/congress-legislators/legislators-current.json';
const zipDistrictUrl = 'https://raw.githubusercontent.com/OpenSourceActivismTech/us-zipcodes-congress/master/zccd.csv';
const rosterFile = 'src/representatives.ts';
const zipDistrictFile = 'src/zip-districts.ts';

function formatDate(date) {
  return new Intl.DateTimeFormat('en-US', { month: 'long', day: 'numeric', year: 'numeric', timeZone: 'UTC' }).format(date);
}

async function fetchText(url) {
  const response = await fetch(url, { headers: { 'User-Agent': 'CapitolHillCrawlerCivicsUpdater/1.0' } });
  if (!response.ok) throw new Error(`Could not fetch ${url}: ${response.status}`);
  return response.text();
}

const [rosterJson, zipCsv] = await Promise.all([fetchText(rosterUrl), fetchText(zipDistrictUrl)]);

const representativesByState = {};
for (const legislator of JSON.parse(rosterJson)) {
  const term = legislator.terms[legislator.terms.length - 1];
  // Delegates and the Resident Commissioner also use type 'rep'. They are the correct answer
  // for their jurisdiction, so they belong here alongside voting members.
  if (term.type !== 'rep') continue;
  const name = legislator.name.official_full ?? `${legislator.name.first} ${legislator.name.last}`;
  // At-large states and every territory report no district number; 0 is the shared convention
  // used by the ZIP source for the same seats.
  (representativesByState[term.state] ??= []).push({ district: term.district ?? 0, name });
}

for (const entries of Object.values(representativesByState)) entries.sort((left, right) => left.district - right.district);

const memberCount = Object.values(representativesByState).reduce((total, entries) => total + entries.length, 0);
if (memberCount < 420) throw new Error(`Roster source returned only ${memberCount} House members.`);
if (Object.keys(representativesByState).length < 56) throw new Error('Roster source did not return all 56 House jurisdictions.');

// Keyed by state *and* ZIP: 109 ZIP codes straddle a state line, and merging those on ZIP alone
// would attribute a neighbouring state's districts to the wrong state.
const districtsByStateZip = new Map();
for (const row of zipCsv.trim().split('\n').slice(1)) {
  const [, rawState, rawZip, rawDistrict] = row.split(',');
  if (!rawState || !rawZip || rawDistrict === undefined) continue;
  const state = rawState.trim();
  const zip = rawZip.trim().padStart(5, '0');
  const key = `${state}:${zip}`;
  const entry = districtsByStateZip.get(key) ?? { state, zip, districts: new Set() };
  entry.districts.add(Number(rawDistrict.trim()));
  districtsByStateZip.set(key, entry);
}

const uniqueZips = new Set([...districtsByStateZip.values()].map((entry) => entry.zip));
if (uniqueZips.size < 30_000) throw new Error(`ZIP source returned only ${uniqueZips.size} ZIP codes.`);

// A district with no seated member is a real vacancy, not a data error. The game falls back to
// state-wide acceptance for those, so this reports rather than fails.
const seated = new Set(Object.entries(representativesByState).flatMap(([state, entries]) => entries.map((entry) => `${state}-${entry.district}`)));
const vacant = new Set();
for (const entry of districtsByStateZip.values()) {
  for (const district of entry.districts) {
    if (!seated.has(`${entry.state}-${district}`)) vacant.add(`${entry.state}-${district}`);
  }
}
if (vacant.size) console.warn(`Districts with no seated member (treated as vacancies): ${[...vacant].sort().join(', ')}`);

const zipLines = [...districtsByStateZip.values()]
  .sort((left, right) => (left.zip === right.zip ? (left.state < right.state ? -1 : 1) : left.zip < right.zip ? -1 : 1))
  .map((entry) => `${entry.zip}:${entry.state}:${[...entry.districts].sort((a, b) => a - b).join('.')}`);

const verifiedOn = JSON.stringify(formatDate(new Date()));

const rosterGenerated = `// Generated by scripts/update-representatives.mjs from official public sources.
// This file is automatically refreshed on the 1st of each month. Do not edit it by hand.
// Logic that depends on this data belongs in a separate module; this file is overwritten wholesale.

export type Representative = { district: number; name: string };

export const representativeDataLastVerified = ${verifiedOn};

/** Keyed by two-letter code. District 0 is an at-large seat, a Delegate, or the Resident Commissioner. */
export const representativesByState: Record<string, Representative[]> = ${JSON.stringify(representativesByState, null, 2)};

export const representativeSources = {
  roster: ${JSON.stringify(rosterUrl)},
  districts: ${JSON.stringify(zipDistrictUrl)},
  note: 'ZIP codes resolve to districts entirely in the browser. No lookup request ever leaves the device.'
};
`;

const zipGenerated = `// Generated by scripts/update-representatives.mjs from ${zipDistrictUrl}.
// This file is automatically refreshed on the 1st of each month. Do not edit it by hand.
// Logic that depends on this data belongs in a separate module; this file is overwritten wholesale.
//
// One line per ZIP code per state, as "ZIP:STATE:district[.district...]". About a fifth of ZIP
// codes span more than one district, and a hundred or so straddle a state line and appear twice.
// Shipped as a single string and parsed on demand: it is far cheaper to parse than an object
// literal with this many keys, and src/zip-lookup.ts imports it lazily so it never reaches the
// initial bundle.

export const zipDistrictTable = \`${zipLines.join('\n')}\`;
`;

writeFileSync(rosterFile, rosterGenerated, 'utf8');
writeFileSync(zipDistrictFile, zipGenerated, 'utf8');
console.log(`Updated ${rosterFile} with ${memberCount} House members across ${Object.keys(representativesByState).length} jurisdictions.`);
console.log(`Updated ${zipDistrictFile} with ${uniqueZips.size} ZIP codes (${zipLines.length} state/ZIP pairs).`);
