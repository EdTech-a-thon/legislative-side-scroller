import { readFileSync, writeFileSync } from 'node:fs';

const senateUrl = 'https://www.senate.gov/general/contact_information/senators_cfm.xml';
const governorsUrl = 'https://www.nga.org/governors/';
const dataFile = 'src/officeholders.ts';

function decode(value) {
  return value.replace(/&amp;/g, '&').replace(/&#8217;/g, "'").trim();
}

function matches(value, pattern) {
  return value.match(pattern)?.[1]?.trim() ?? '';
}

function formatDate(date) {
  return new Intl.DateTimeFormat('en-US', { month: 'long', day: 'numeric', year: 'numeric', timeZone: 'UTC' }).format(date);
}

async function fetchText(url) {
  const response = await fetch(url, { headers: { 'User-Agent': 'CapitolHillCrawlerCivicsUpdater/1.0' } });
  if (!response.ok) throw new Error(`Could not fetch ${url}: ${response.status}`);
  return response.text();
}

const [senateXml, governorsHtml] = await Promise.all([fetchText(senateUrl), fetchText(governorsUrl)]);
const senatorsByState = {};

for (const member of senateXml.matchAll(/<member>([\s\S]*?)<\/member>/g)) {
  const record = member[1];
  const state = matches(record, /<state>([^<]+)<\/state>/);
  const first = matches(record, /<first_name>([^<]+)<\/first_name>/);
  const last = matches(record, /<last_name>([^<]+)<\/last_name>/);
  if (!state || !first || !last) continue;
  (senatorsByState[state] ??= []).push(decode(`${first} ${last}`));
}

const stateNames = [
  'Alabama','Alaska','Arizona','Arkansas','California','Colorado','Connecticut','Delaware','Florida','Georgia','Hawaii','Idaho','Illinois','Indiana','Iowa','Kansas','Kentucky','Louisiana','Maine','Maryland','Massachusetts','Michigan','Minnesota','Mississippi','Missouri','Montana','Nebraska','Nevada','New Hampshire','New Jersey','New Mexico','New York','North Carolina','North Dakota','Ohio','Oklahoma','Oregon','Pennsylvania','Rhode Island','South Carolina','South Dakota','Tennessee','Texas','Utah','Vermont','Virginia','Washington','West Virginia','Wisconsin','Wyoming'
];
const governorsByState = {};
for (const stateName of stateNames) {
  const start = governorsHtml.indexOf(`${stateName}</small>`);
  if (start < 0) continue;
  const nearby = governorsHtml.slice(start, start + 2500);
  const governor = nearby.match(/Gov\.\s*([^<\n]+)/)?.[1]?.trim();
  if (governor) governorsByState[stateName] = decode(governor);
}

if (Object.keys(senatorsByState).length < 50) throw new Error('Senate source did not return all 50 state delegations.');
if (Object.keys(governorsByState).length < 50) throw new Error('Governor source did not return all 50 governors.');

const generated = `// Generated by scripts/update-officeholders.mjs from official public sources.\n// This file is automatically refreshed on January 28 and August 28.\n\nexport const officeholderDataLastVerified = ${JSON.stringify(formatDate(new Date()))};\n\nexport const senatorsByState: Record<string, string[]> = ${JSON.stringify(senatorsByState, null, 2)};\n\nexport const governorsByStateName: Record<string, string> = ${JSON.stringify(governorsByState, null, 2)};\n\nexport const nationalOfficeholders: Record<number, string[]> = {\n  30: ['Mike Johnson'],\n  38: ['Donald Trump'],\n  39: ['JD Vance', 'James David Vance'],\n  57: ['John Roberts', 'John G Roberts']\n};\n\nexport const officeholderSources = {\n  senators: ${JSON.stringify(senateUrl)},\n  governors: ${JSON.stringify(governorsUrl)},\n  note: 'U.S. Representatives require a separate district-level location or ZIP lookup and are not stored here.'\n};\n`;

writeFileSync(dataFile, generated, 'utf8');
console.log(`Updated ${dataFile} with ${Object.keys(senatorsByState).length} Senate delegations and ${Object.keys(governorsByState).length} governors.`);
